export function normalizeText(text: string) {
  return text.toLowerCase().replace(/\s+/g, " ").trim();
}

export function includesAny(text: string, keywords: string[]) {
  return keywords.some((keyword) => text.includes(keyword));
}

export function isPriceQuestion(text: string) {
  return includesAny(normalizeText(text), PRICE_KEYWORDS);
}

export function isPromotionQuestion(text: string) {
  return includesAny(normalizeText(text), PROMOTION_KEYWORDS);
}

// ถามลอยๆ ว่า "มี...ไหม" แต่ถ้าเป็นการเล่าอาการ เช่น "ไม่มีแก๊ส" "มีปัญหาไหม" ไม่นับว่าถามสินค้า
const HAS_PRODUCT_QUESTION = /มี.{0,40}(ไหม|มัย|หรือเปลา|หรือไม|รึเปลา|ปาว)/;
const NOT_PRODUCT_QUESTION = ["ไม่มี", "มีปัญหา", "มีอาการ", "มีเสียง"];

export function isPartsQuestion(text: string) {
  return includesAny(compactText(text), PART_KEYWORDS.map(compactText));
}

export function isStockQuestion(text: string) {
  if (includesAny(normalizeText(text), STOCK_KEYWORDS) || isPartsQuestion(text)) return true;
  const compact = compactText(text);
  if (includesAny(compact, NOT_PRODUCT_QUESTION.map(compactText))) return false;
  return HAS_PRODUCT_QUESTION.test(compact);
}

export function isGreeting(text: string) {
  const normalized = normalizeText(text);
  if (normalized.length > 20) return false;
  if (includesAny(normalized, GREETING_KEYWORDS)) return true;
  return normalized.split(/[^a-z]+/).some((word) => GREETING_WORDS.includes(word));
}

// ตัดช่องว่างและวรรณยุกต์ออก และรวมคำสะกดของแก๊ส ให้ "แก๊ส รั่ว" "แก็สรั่ว" "ก๊าซรั่ว" ถูกมองเป็นคำเดียวกัน
export function compactText(text: string) {
  return normalizeText(text).replace(/[\s\u0E47-\u0E4B]/g, "").replace(/แกซ|กาซ/g, "แกส");
}

const GAS_WORDS = ["แกส", "แก็ส", "แก๊ส", "ก๊าซ", "กาซ", "แก็ซ", "gas", "lpg"].map(compactText);
const LEAK_WORDS = ["รั่ว", "ซึม", "ฟู่", "พ่น", "leak"].map(compactText);
const ODOR_WORDS = ["กลิ่น", "เหม็น", "smell", "odor"].map(compactText);
// เรื่องหัวปรับ/ข้อต่อรั่ว มีคำตอบเฉพาะของตัวเอง (ซึ่งเริ่มด้วยการปิดวาล์วและเปิดหน้าต่างอยู่แล้ว)
const REGULATOR_WORDS = ["หัวปรับ", "วาล์ว", "ข้อต่อ", "รอยต่อ", "สายแก๊ส", "สายยาง"].map(compactText);

/**
 * ตรวจว่าเป็นเหตุแก๊สรั่วหรือไม่ ใช้ก่อนทุกอย่าง (ก่อนทักทาย/ราคา) เพราะเป็นเรื่องความปลอดภัย
 * - มีกลิ่น/เหม็น = เหตุฉุกเฉินเสมอ แม้จะไม่ได้พิมพ์คำว่าแก๊สหรือพูดถึงหัวปรับด้วย เพราะถ้าทักผิดก็ไม่อันตราย
 * - ถ้าพูดถึงหัวปรับ/ข้อต่อ/สาย (ไม่มีกลิ่น) ให้ไปที่คำตอบเฉพาะของหัวปรับ
 * - นอกนั้นนับ keyword ใน FAQ หรือคำว่าแก๊สปนกับรั่ว ไม่ว่าจะเว้นวรรคหรือสะกดต่างกัน
 */
export function isGasLeak(text: string) {
  const compact = compactText(text);
  if (!compact) return false;
  const has = (words: string[]) => words.some((word) => compact.includes(word));

  if (has(ODOR_WORDS)) return true;
  const mentionsGas = has(GAS_WORDS);
  if (has(REGULATOR_WORDS)) return false;
  if (FAQ_ENTRIES[0].keywords.some((keyword) => compact.includes(compactText(keyword)))) return true;
  return mentionsGas && has(LEAK_WORDS);
}

function keywordsFoundIn(compact: string, entry: FaqEntry) {
  return entry.keywords.filter((keyword) => compact.includes(compactText(keyword)));
}

/**
 * อาการอันตราย (emergency/callShop) เจอแค่คำเดียวก็ตอบเลย และตอบก่อนเรื่องอื่นทั้งหมด
 * เช่น "ถังบวม แก๊สไม่ออก" ต้องบอกให้โทรหาร้าน ไม่ใช่ให้ลูกค้าไปแยงนมหนู
 */
export function matchUrgentFaq(text: string): FaqEntry | null {
  if (isGasLeak(text)) return FAQ_ENTRIES[0];
  const compact = compactText(text);
  if (!compact) return null;
  return (
    FAQ_ENTRIES.find((entry) => entry.severity === "emergency" && entry.id !== "gasLeak" && keywordsFoundIn(compact, entry).length > 0) ??
    FAQ_ENTRIES.find((entry) => entry.severity === "callShop" && keywordsFoundIn(compact, entry).length > 0) ??
    null
  );
}

/** หาคำตอบที่ตรงที่สุด อาการอันตรายมาก่อนเสมอ ที่เหลือนับจำนวน keyword ที่เจอในข้อความ */
export function matchFaq(text: string): FaqEntry | null {
  const compact = compactText(text);
  if (!compact) return null;

  const urgent = matchUrgentFaq(text);
  if (urgent) return urgent;

  let best: FaqEntry | null = null;
  let bestScore = 0;
  for (const entry of FAQ_ENTRIES) {
    if (entry.severity === "emergency" || entry.severity === "callShop") continue;
    const score = keywordsFoundIn(compact, entry).length;
    if (score > bestScore) {
      best = entry;
      bestScore = score;
    }
  }
  return best;
}

export function extractSizeKg(text: string): number | null {
  const match = normalizeText(text).match(/(\d+(?:\.\d+)?)\s*(?:กก|กิโล|kg)/);
  if (!match) return null;
  const size = Number(match[1]);
  return Number.isFinite(size) && size > 0 ? size : null;
}
