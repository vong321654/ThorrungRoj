function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <Box component="section" sx={{ mt: 2.5 }}>
      <Typography component="h3" sx={{ fontWeight: 700, fontSize: "1rem", mb: 0.75 }}>
        {title}
      </Typography>
      {children}
    </Box>
  );
}

function Paragraph({ children }: { children: ReactNode }) {
  return (
    <Typography variant="body2" sx={{ mb: 1, lineHeight: 1.7 }}>
      {children}
    </Typography>
  );
}

function BulletList({ items }: { items: ReactNode[] }) {
  return (
    <Box component="ul" sx={{ m: 0, pl: 2.5 }}>
      {items.map((item, index) => (
        <Typography key={index} component="li" variant="body2" sx={{ mb: 0.75, lineHeight: 1.7 }}>
          {item}
        </Typography>
      ))}
    </Box>
  );
}

