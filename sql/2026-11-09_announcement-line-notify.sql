-- =====================================================================
-- บันทึกว่าประกาศถูกส่งเข้าแชท LINE ของลูกค้าแล้วเมื่อใด
--
-- ระบบส่งประกาศเป็น Flex Message (broadcast) ถึงเพื่อนทุกคนของ LINE OA ครั้งแรกที่ประกาศถูกเผยแพร่
-- คอลัมน์นี้กันส่งซ้ำ เมื่อแอดมินกด "ซ่อน" แล้ว "เผยแพร่" ใหม่ หรือแก้ไขข้อความภายหลัง
-- null = ยังไม่เคยส่ง (หรือส่งไม่สำเร็จ ระบบจะลองใหม่เมื่อบันทึกประกาศนั้นอีกครั้ง)
--
-- ต้องรันก่อน deploy โค้ดที่อ่านคอลัมน์นี้ ไม่งั้นหน้าจัดการประกาศของแอดมินจะตอบ 500
-- ประกาศเดิมที่เผยแพร่อยู่แล้วถือว่าส่งไปแล้ว เพื่อไม่ให้ broadcast ประกาศเก่าทั้งหมดทันทีที่มีการแก้ไข
-- =====================================================================
alter table public.announcements
  add column if not exists "lineNotifiedAt" timestamptz;

update public.announcements
set "lineNotifiedAt" = coalesce("publishedAt", "createdAt")
where "isPublished" = true and "lineNotifiedAt" is null;
